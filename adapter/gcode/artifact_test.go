package gcode

import (
	"bytes"
	"strings"
	"testing"
)

// The metadata keys and hex color mirror an inspected PrusaSlicer 2.3.2 file.
const source = "; generated by PrusaSlicer 2.3.2+win64\nG90\nM104 S200\n; filament_colour = #FF8000\n; filament_type = PLA\n"

func TestPrepareAndInspect(t *testing.T) {
	var out bytes.Buffer
	options := Options{ExecutionID: "job-1", ProfileID: "ender3", ProfileVersion: "v1"}
	artifact, err := Prepare(strings.NewReader(source), &out, options)
	if err != nil {
		t.Fatal(err)
	}
	if artifact.Material != "PLA" || artifact.Color != "C_FF8000" {
		t.Fatalf("wrong metadata: %+v", artifact)
	}
	if !strings.HasSuffix(out.String(), source) {
		t.Fatal("original bytes changed")
	}
	inspected, err := Inspect(bytes.NewReader(out.Bytes()))
	if err != nil || inspected != artifact {
		t.Fatalf("inspect: %+v %v", inspected, err)
	}
	var repeated bytes.Buffer
	if _, err := Prepare(bytes.NewReader(out.Bytes()), &repeated, options); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(out.Bytes(), repeated.Bytes()) {
		t.Fatal("preparing twice changed the file")
	}
	options.ExecutionID = "job-2"
	if _, err := Prepare(bytes.NewReader(out.Bytes()), &bytes.Buffer{}, options); err == nil {
		t.Fatal("execution context replaced")
	}
}

func TestRejectsUnsafeMetadataAndHooks(t *testing.T) {
	for _, input := range []string{
		"G90\n; filament_type = PLA;PETG\n",
		"G90\n; filament_type = PLA\n; filament_type = PETG\n",
		"PCMA_PRINT_START EXECUTION=other\n; filament_type = PLA\n",
		"G90\nT1\n; filament_type = PLA\n",
		"G90\nT7\n; filament_type = PLA\n",
	} {
		if _, err := Prepare(strings.NewReader(input), &bytes.Buffer{}, Options{ExecutionID: "job-1", ProfileID: "ender3", ProfileVersion: "v1"}); err == nil {
			t.Errorf("accepted %q", input)
		}
	}
	if _, err := Prepare(strings.NewReader(source), &bytes.Buffer{}, Options{ExecutionID: "x\nG28", ProfileID: "ender3", ProfileVersion: "v1"}); err == nil {
		t.Fatal("accepted executable execution ID")
	}
	if _, err := Prepare(strings.NewReader(source), &bytes.Buffer{}, Options{ExecutionID: "job", ProfileID: "ender3", ProfileVersion: "v1", Material: "PETG"}); err == nil {
		t.Fatal("accepted conflicting material")
	}
}

func TestExistingEarlyHookIsPreserved(t *testing.T) {
	input := "PCMA_PRINT_START COLOR=WHITE MATERIAL=PLA EXECUTION=job-1\nG90\n; filament_type = PLA\n"
	var out bytes.Buffer
	options := Options{ExecutionID: "job-1", ProfileID: "ender3", ProfileVersion: "1.0.0", Color: "WHITE"}
	if _, err := Prepare(strings.NewReader(input), &out, options); err != nil {
		t.Fatal(err)
	}
	if strings.Count(out.String(), "PCMA_PRINT_START") != 1 || !strings.HasSuffix(out.String(), input) {
		t.Fatal("existing hook was duplicated or original bytes changed")
	}
	if _, err := Inspect(bytes.NewReader(out.Bytes())); err != nil {
		t.Fatal(err)
	}
}

func TestRetainedOriginalHashAndLineEndings(t *testing.T) {
	input := strings.ReplaceAll(source, "\n", "\r\n")
	var out bytes.Buffer
	_, err := Prepare(strings.NewReader(input), &out, Options{ExecutionID: "job-hash", ProfileID: "ender3", ProfileVersion: "1.0.0", Color: "#FFFFFF"})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasSuffix(out.String(), input) {
		t.Fatal("source line endings changed")
	}
	if _, err := Inspect(bytes.NewReader(out.Bytes())); err != nil {
		t.Fatal(err)
	}
	changed := strings.Replace(out.String(), "M104 S200", "M104 S210", 1)
	if _, err := Inspect(strings.NewReader(changed)); err == nil {
		t.Fatal("tampered retained source passed original hash check")
	}
}
